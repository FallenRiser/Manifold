"""Honest numbers for the Building-environments track.

Every figure quoted on a World 1 page in /learn/building-environments is produced
here, by running the SHIPPED environment code (src/lib/runtimeSetup.ts -> ENV_SETUP).

    python scripts/env_cases.py w1

The setup string is extracted from the TypeScript so what is verified here is
byte-identical to what the browser's Run button executes.
"""

import math
import re
import sys
import time
import pathlib

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]


def load_setup(name="ENV_SETUP"):
    src = (ROOT / "src" / "lib" / "runtimeSetup.ts").read_text(encoding="utf-8")
    m = re.search(r"export const " + name + r" = `(.*?)\n`;", src, re.S)
    if not m:
        raise SystemExit(f"{name} not found in runtimeSetup.ts")
    body = m.group(1).replace("\\\\u", "\\u").replace("\\\\n", "\\n")
    ns = {}
    exec(compile(body, f"<{name}>", "exec"), ns)
    return ns


G = load_setup()


def fmt(d):
    return {k: (round(v, 2) if isinstance(v, float) else v) for k, v in d.items()}


def w1():
    print(f"oracle: best angle {G['BEST_ANGLE']:.2f} deg, VMG {G['BEST_VMG']:.4f} m/s")
    rr = np.random.default_rng(0)
    print("random ", fmt(G["race"](lambda env: (lambda o: int(rr.integers(3))))))
    print("hold   ", fmt(G["race"](lambda env: (lambda o: 1))))
    print("expert ", fmt(G["race"](G["expert"])))

    experiments = [
        ("progress", "penalty", 5),
        ("time", "free", 3),
        ("time", "penalty", 3),
        ("time", "none", 3),
        ("speed", "penalty", 3),
    ]
    for reward, edge, seeds in experiments:
        t0 = time.time(); rows = []
        for seed in range(seeds):
            Q, log = G["train_sailor"](reward, edge, seed=seed)
            r = G["race"](G["greedy"](Q), edge)
            r["train_out_last200"] = sum(l[1] for l in log[-200:])
            rows.append(r)
        arr = [r["arrived"] for r in rows]
        print(f"\n[{reward} / {edge}] {(time.time() - t0) / seeds:.1f}s/seed  arrivals {arr}  "
              f"mean {np.mean(arr):.1f} sd {np.std(arr):.1f}")
        for r in rows:
            print("   ", fmt(r))


def trunc():
    """Terminated vs truncated at the race clock: bootstrap at the buzzer, or treat it as the end?"""
    for clock in (200, 80):
        for boot in (True, False):
            t0 = time.time(); arr = []
            for seed in range(5):
                Q, _ = G["train_sailor"](seed=seed, clock=clock, bootstrap_truncation=boot)
                arr.append(G["race"](G["greedy"](Q), clock=clock)["arrived"])
            label = "bootstrap at the buzzer" if boot else "zero at the buzzer"
            print(f"clock {clock:3d}  {label:24s} arrivals {arr}  mean {np.mean(arr):.1f} sd {np.std(arr):.1f}"
                  f"  ({(time.time() - t0) / 5:.1f}s/seed)", flush=True)


def _race_record(env, pol, keep_cells=False):
    "Sail one race from the env's current reset state and record every second."
    rec = dict(x=[env.x], y=[env.y], h=[env.h], u=[env.u])
    cells = []
    o = (env.x, env.y, env.h, env.u)
    while True:
        if keep_cells: cells.append(G["observe"](o, env))
        o, r, te, tr, info = env.step(pol(o))
        rec["x"].append(env.x); rec["y"].append(env.y); rec["h"].append(env.h); rec["u"].append(env.u)
        if te or tr: break
    rec["end"] = "arrived" if info["arrived"] else ("out" if info["out"] else "clock")
    rec["tacks"] = env.tacks
    if keep_cells: rec["cells"] = cells
    return rec


def _compact(rec, label, **extra):
    out = dict(label=label, end=rec["end"], tacks=rec["tacks"],
               x=[round(v, 2) for v in rec["x"]], y=[round(v, 2) for v in rec["y"]],
               h=[round(v, 1) for v in rec["h"]], u=[round(v, 3) for v in rec["u"]])
    if "cells" in rec: out["cells"] = rec["cells"]
    out.update(extra)
    return out


def _write(name, const, races, note):
    import json
    path = ROOT / "src" / "components" / "sail" / "data" / f"{name}.ts"
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(races, separators=(",", ":"))
    path.write_text(
        f"// Generated by running the shipped ENV_SETUP ({note}). Do not edit by hand.\n"
        f'import type {{ Race }} from "../types";\n\n'
        f"export const {const}: Race[] = {body};\n", encoding="utf-8")
    print(f"wrote {path.name}: " + ", ".join(f"{r['label']} {len(r['x']) - 1} s {r['end']}" for r in races))


def _train_with_snapshots(checkpoints, reward="progress", edge="penalty", episodes=2000, seed=0,
                          alpha=0.5, gamma=0.99, eps0=0.1):
    "train_sailor, line for line, pausing to copy the table after the given numbers of races."
    env = G["Sail"](reward, edge); rng = np.random.default_rng(seed)
    Q = np.zeros((G["N_STATES"], 3)); snaps = {}
    for ep in range(episodes):
        o, _ = env.reset(seed=seed * 100000 + ep); s = G["observe"](o, env)
        eps = eps0 * max(0.0, 1 - ep / episodes)
        while True:
            a = int(rng.integers(3)) if rng.random() < eps else int(np.argmax(Q[s]))
            o, r, te, tr, info = env.step(a); s2 = G["observe"](o, env)
            Q[s, a] += alpha * (r + (0.0 if te else gamma * Q[s2].max()) - Q[s, a]); s = s2
            if te or tr: break
        if ep + 1 in checkpoints: snaps[ep + 1] = Q.copy()
    return snaps


def export():
    """Exact race tracks for the replay figures on the World 1 pages."""
    Sail, expert, greedy = G["Sail"], G["expert"], G["greedy"]

    def point_at_mark(env):
        def helm(o):
            x, y, h, u = o
            err = G["wrap"](math.degrees(math.atan2(env.mx - x, env.my - y)) - h)
            return 1 if abs(err) < 5 else (2 if err > 0 else 0)
        return helm

    # hub: the three helms of the first cell (one shared rng, one env, seed 3)
    rng = np.random.default_rng(0); env = Sail(); races = []
    for label, helm in (("random helm", lambda o: int(rng.integers(3))), ("hold the tiller", lambda o: 1),
                        ("a sailor who can tack", expert(env))):
        env.reset(seed=3); races.append(_compact(_race_record(env, helm), label))
    _write("hubRaces", "HUB_RACES", races, "hub page, start seed 3")

    # brief: point at the mark from seeds 3, 4, 5
    races = []
    for seed in (3, 4, 5):
        env = Sail(); env.reset(seed=seed)
        races.append(_compact(_race_record(env, point_at_mark(env)), f"start seed {seed}"))
    _write("briefRaces", "BRIEF_RACES", races, "the brief, point-at-the-mark helm")

    # sanity ladder: held-out race 0 for each helm (the random helm's rng is fresh, as in the ladder)
    rng = np.random.default_rng(0); races = []
    for label, make in (("random helm", lambda env: (lambda o: int(rng.integers(3)))),
                        ("hold the tiller", lambda env: (lambda o: 1)),
                        ("point at the mark", point_at_mark), ("the expert", expert)):
        env = Sail(); env.reset(seed=10**6)
        races.append(_compact(_race_record(env, make(env)), label))
    _write("sanityRaces", "SANITY_RACES", races, "sanity ladder, held-out race 0")

    # the edge: -1 per second, trained with each edge (seed 0), held-out race 0
    races = []
    for edge in ("none", "free", "penalty"):
        Q, _ = G["train_sailor"](reward="time", edge=edge, seed=0)
        env = Sail("time", edge); env.reset(seed=10**6)
        races.append(_compact(_race_record(env, greedy(Q)(env)), f"edge={edge}"))
    _write("edgeRaces", "EDGE_RACES", races, "-1 per second, seed 0, held-out race 0")

    # paying: frozen vs still-learning, on the first held-out race where frozen ends stuck and learning finishes
    Q, _ = G["train_sailor"](reward="time", seed=0)
    for k in range(200):
        pair = []
        for keep in (False, True):
            q = Q.copy(); env = Sail("time"); o, _ = env.reset(seed=10**6 + k); s = G["observe"](o, env)
            rec = dict(x=[env.x], y=[env.y], h=[env.h], u=[env.u]); cells = []
            while True:
                a = int(np.argmax(q[s]))
                o, r, te, tr, info = env.step(a); s2 = G["observe"](o, env)
                if keep: q[s, a] += 0.5 * (r + (0.0 if te else 0.99 * q[s2].max()) - q[s, a])
                cells.append(s); s = s2
                for key, v in zip("xyhu", o): rec[key].append(v)
                if te or tr: break
            rec.update(end="arrived" if info["arrived"] else ("out" if info["out"] else "clock"),
                       tacks=env.tacks, cells=cells)
            pair.append((rec, tr and len(set(cells[-50:])) == 1))
        (frozen, stuck), (learning, _) = pair
        if stuck and learning["end"] == "arrived":
            _write("payingRaces", "PAYING_RACES",
                   [_compact(frozen, "table frozen", race=k), _compact(learning, "table still learning", race=k)],
                   f"-1 per second, seed 0, held-out race {k}: the first where frozen is stuck and learning finishes")
            break

    # tacking: races 0 and 1 of the shipped boat, and race 0 at checkpoints of the same training run
    Q, _ = G["train_sailor"](seed=0)
    races = []
    for k in (0, 1):
        env = Sail(); env.reset(seed=10**6 + k)
        races.append(_compact(_race_record(env, greedy(Q)(env)), f"held-out race {k}"))
    _write("tackRaces", "TACK_RACES", races, "shipped boat, seed 0")
    cps = (100, 250, 500, 1000, 2000)
    snaps = _train_with_snapshots(set(cps))
    assert np.array_equal(snaps[2000], Q), "snapshot training diverged from train_sailor"
    races = []
    for c in cps:
        env = Sail(); env.reset(seed=10**6)
        arr = G["race"](greedy(snaps[c]))["arrived"]
        races.append(_compact(_race_record(env, greedy(snaps[c])(env)), f"after {c} races", practice=c, finishes=arr))
    _write("filmstripRaces", "FILMSTRIP_RACES", races, "shipped boat, seed 0, the same run paused at each checkpoint")

    # speed: held-out race 0 of the speed-paid boat
    Q, _ = G["train_sailor"](reward="speed", seed=0)
    env = Sail("speed"); env.reset(seed=10**6)
    _write("speedRaces", "SPEED_RACES", [_compact(_race_record(env, greedy(Q)(env)), "paid for speed")],
           "speed-paid boat, seed 0, held-out race 0")


