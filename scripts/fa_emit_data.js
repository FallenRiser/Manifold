// Turn the captured stdout of scripts/fa_figures.py into
// src/components/figures/fa/data.ts.
//
//   python scripts/fa_figures.py > out.txt
//   node scripts/fa_emit_data.js out.txt
//
// Hand-copying forty numeric arrays out of a terminal is how a figure quietly
// stops describing the run it claims to describe. This reads the arrays the
// script printed and writes the module, so the only way for the data to drift
// is for someone to skip re-running it.

const fs = require("fs");
const path = require("path");

const SRC = process.argv[2];
if (!SRC) {
  console.error("usage: node scripts/fa_emit_data.js <captured-output.txt>");
  process.exit(2);
}
const text = fs.readFileSync(SRC, "utf8");

// NAME = [ ... ]  possibly spanning many lines, values comma-separated.
const arrays = {};
const re = /^([A-Z][A-Z0-9_]*) = \[\s*\n([\s\S]*?)\n\]\s*$/gm;
let m;
while ((m = re.exec(text))) {
  const body = m[2];
  if (/^\s*\[/.test(body)) {
    // matrix: rows of the form "  [a, b, c],"
    arrays[m[1]] = body
      .split("\n")
      .map((l) => l.trim().replace(/^\[|\],?$/g, ""))
      .filter(Boolean)
      .map((l) => l.split(",").map((v) => Number(v.trim())));
  } else {
    arrays[m[1]] = body
      .split(",")
      .map((v) => v.trim())
      .filter(Boolean)
      .map(Number);
  }
}
// single-line form: NAME = [a, b, c]
const re1 = /^([A-Z][A-Z0-9_]*) = \[([^\n\]]*)\]\s*$/gm;
while ((m = re1.exec(text))) {
  if (arrays[m[1]]) continue;
  arrays[m[1]] = m[2].split(",").map((v) => v.trim()).filter(Boolean).map(Number);
}

const names = Object.keys(arrays).sort();
if (!names.length) {
  console.error("no arrays found in " + SRC);
  process.exit(1);
}

const fmt = (v) => (Number.isInteger(v) ? String(v) : String(v));
const wrap = (vals, indent) => {
  const out = [];
  let line = indent;
  for (const v of vals) {
    const s = fmt(v) + ", ";
    if (line.length + s.length > 96) {
      out.push(line.trimEnd());
      line = indent;
    }
    line += s;
  }
  if (line.trim()) out.push(line.trimEnd());
  return out.join("\n");
};

let ts = `// GENERATED by scripts/fa_emit_data.js from the stdout of
// scripts/fa_figures.py. Do not edit by hand — re-run both.
//
// scripts/fa_figures.py loads the shipped FA_SETUP out of runtimeSetup.ts and
// runs it, so every series below comes from the same environment code the Run
// button on these pages executes.

`;

for (const n of names) {
  const v = arrays[n];
  if (Array.isArray(v[0])) {
    ts += `export const ${n}: number[][] = [\n`;
    for (const row of v) ts += `  [${row.join(", ")}],\n`;
    ts += `];\n\n`;
  } else {
    ts += `export const ${n}: number[] = [\n${wrap(v, "  ")}\n];\n\n`;
  }
}

const OUT = path.join("src", "components", "figures", "fa", "data.generated.ts");
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts);
console.log(`wrote ${OUT}: ${names.length} arrays`);
for (const n of names) {
  const v = arrays[n];
  console.log(`  ${n.padEnd(18)} ${Array.isArray(v[0]) ? `${v.length}x${v[0].length}` : `${v.length}`}`);
}
